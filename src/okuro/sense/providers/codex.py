    def enforcement_capability(self) -> dict:
        return {
            "provider": self.name,
            "blocking_pre_tool": True,
            # INPUT shape pinned by observing a REAL payload, not by reading
            # docs: an isolated CODEX_HOME with a dumping PreToolUse hook,
            # one `codex exec` turn, captured verbatim:
            #   {"session_id":..., "turn_id":..., "transcript_path":...,
            #    "cwd":"/tmp", "hook_event_name":"PreToolUse",
            #    "model":"gpt-5.5", "permission_mode":"bypassPermissions",
            #    "tool_name":"Bash", "tool_input":{"command":"echo okuro-probe"},
            #    "tool_use_id":"call_..."}
            # It is IDENTICAL to Claude Code's PreToolUse input, down to the
            # field names — which no documentation or web source stated.
            "shell_tool": "Bash",
            "command_field": "tool_input.command",
            # COVERAGE, corrected 2026-07-29. The record said "Bash only".
            # openai/codex#20204 (OPEN, updated 2026-06-14) measures which
            # handlers actually implement pre_tool_use_payload: shell,
            # unified_exec, apply_patch and mcp. Every other handler returns
            # the trait default None. So it is 4 handlers — not 1, and not the
            # "all local function tools" the vendor doc claims. apply_patch
            # and mcp are gateable on Codex today and okuro is not using them.
            "tool_coverage": ("shell", "unified_exec", "apply_patch", "mcp"),
            # STILL UNPINNED, deliberately. Returning {"decision":"allow"} made
            # Codex log `hook: PreToolUse Failed`, so that shape is wrong. The
            # binary embeds `permissionDecision` and `hookSpecificOutput`,
            # which is Claude Code's PreToolUse OUTPUT shape, so it very
            # probably mirrors that too — but "very probably" is what a guessed
            # gate is made of, and a wrong deny shape yields a hook that runs,
            # logs nothing useful, and never blocks. Two attempts to confirm it
            # timed out without capturing. Left None until observed.
            "deny_contract": None,
            "verified": "2026-07-27 — input shape captured from a live "
                        "PreToolUse payload (isolated CODEX_HOME); deny shape "
                        "attempted twice and NOT captured. 2026-07-29 — hook "
                        "coverage corrected to 4 handlers per openai/codex"
                        "#20204 (OPEN); hooks are now enabled by default "
                        "([features] hooks = false disables), and "
                        "allow_managed_hooks_only in requirements.toml lets an "
                        "enterprise deployment ignore okuro's hooks entirely",
            "degradation": (
                "capability and input shape confirmed, but no okuro gate is "
                "emitted for Codex — enforcement here is instructions-only "
                "until the deny contract is observed rather than inferred. "
                "Coverage is 4 tool handlers (shell, unified_exec, "
                "apply_patch, mcp), NOT all tools — upstream issue open, so "
                "any Codex gate covers those four and nothing else"
            ),
        }

    def install_hooks(self) -> list[str]:
        """Install the UserPromptSubmit command hook + refresh its payload cache.

        Codex reads command hooks from ``~/.codex/hooks.json`` (merged with any
        inline ``[hooks]`` tables in config.toml). We write the hook script and
        register it merge-safely, preserving any user-authored hooks. The
        payload comes from the shared ``~/.okuro/profile-turn-context.txt``
        cache, refreshed here so the hook has something to inject.
        """
        generated: list[str] = []
        codex_dir = os.path.expanduser("~/.codex")
        hooks_dir = os.path.join(codex_dir, "hooks")
        try:
            os.makedirs(hooks_dir, exist_ok=True)
        except OSError as e:
            log.warning("codex: cannot create hooks dir (%s); skipping hook install", e)
            return generated

        from ._profile_compliance import atomic_write_json, write_profile_turn_context

        # 1. Hook script.
        hook_path = os.path.join(hooks_dir, self._HOOK_FILENAME)
        try:
            from ._profile_compliance import atomic_write_text
            atomic_write_text(hook_path, USER_PROMPT_HOOK)
            os.chmod(hook_path, 0o755)
            generated.append(hook_path)
        except OSError as e:
            log.warning("codex: hook script write failed: %s", e)
            return generated

        # 2. Register in hooks.json (merge-safe).
        hooks_json_path = os.path.join(codex_dir, "hooks.json")
        try:
            merged = self._merge_hooks_json(hooks_json_path, hook_path)
            atomic_write_json(hooks_json_path, merged)
            generated.append(hooks_json_path)
        except Exception as e:  # noqa: BLE001
            log.warning("codex: hooks.json merge failed: %s", e)

        # 3. Refresh the shared per-turn payload cache.
        try:
            generated.append(write_profile_turn_context())
        except Exception as e:  # noqa: BLE001
            log.warning("codex: profile-turn-context.txt refresh failed: %s", e)

        log.info(
            "codex: installed UserPromptSubmit hook %s. Trust it once via the "
            "`/hooks` command inside codex (non-managed command hooks are "
            "skipped until trusted).",
            hook_path,
        )
        return generated

    def _merge_hooks_json(self, hooks_json_path: str, hook_path: str) -> dict:
        """Return the hooks.json dict with okuro's UserPromptSubmit group merged in.

        Preserves every other event and every non-okuro handler group. Ours is
        identified by an inner handler whose ``command`` references our script
        basename, so a re-install replaces rather than duplicates it.
        """
        data: dict = {}
        if os.path.isfile(hooks_json_path):
            try:
                with open(hooks_json_path) as f:
                    loaded = json.load(f)
                if isinstance(loaded, dict):
                    data = loaded
            except (OSError, json.JSONDecodeError) as e:
                log.warning("codex: hooks.json unreadable/corrupt (%s); rewriting fresh", e)
                data = {}

        hooks_block = data.get("hooks")
        if not isinstance(hooks_block, dict):
            hooks_block = {}

        groups = hooks_block.get("UserPromptSubmit")
        if not isinstance(groups, list):
            groups = []

        basename = os.path.basename(hook_path)

        def _is_ours(group: object) -> bool:
            if not isinstance(group, dict):
                return False
            inner = group.get("hooks")
            if not isinstance(inner, list):
                return False
            for h in inner:
                if isinstance(h, dict) and basename in str(h.get("command", "")):
                    return True
            return False

        cleaned = [g for g in groups if not _is_ours(g)]
        cleaned.append({
            "hooks": [
                {
                    "type": "command",
                    "command": f'python3 "{hook_path}"',
                    "timeout": 10,
                    "statusMessage": "okuro: injecting profile context",
                }
            ],
        })

        hooks_block["UserPromptSubmit"] = cleaned
        data["hooks"] = hooks_block
        return data

    def get_subagent_protocol(self, bootstrap_context: str) -> str:
        from .template import build_subagent_protocol
        return build_subagent_protocol()
