# installer, and has no use for how okuro builds itself. Engineering rationale
# belongs in Python comments like this one — MEASURED: `#` comments and
# docstrings in this module never land in a generated file, only the
# `_INSTRUCTIONS_TEMPLATE` and `_*_EXTRAS` literals do.
#
# The "Auto-generated by okuro. Do not edit manually." line used to head the
# emitted file. It is an install instruction to the owner, delivered to every
# agent on every provider, at the top of the document that claims to bind them.
