"""Shared instruction-template builder for every provider adapter.

Why one template
----------------
Probe evidence (collected 2026-04-26 across claude/codex/gemini CLIs) shows
each MCP-aware client surfaces the same okuro tool with a *different*
agent-facing name:

  - Claude Code:  ``mcp__okuro__bootstrap``    (double underscore)
  - Gemini CLI:   ``mcp_okuro_bootstrap``      (single underscore)
  - Codex CLI:    ``okuro/bootstrap``          (slash; agent self-reports it
                                               inconsistently as ``mcp__okuro__.bootstrap``)

Hardcoding any of these strings into a per-provider template means the
template breaks the moment the provider changes convention (Codex's recent
update did exactly this). Every provider adapter therefore consumes this
SHARED template; the directive is *discovery-friendly* — the agent finds
the bootstrap tool by description, not by string match.

This decouples the instructions text from the tool-naming syntax, which
lives in the provider's own MCP layer.
"""

from __future__ import annotations


